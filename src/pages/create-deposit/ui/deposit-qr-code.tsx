function Finder({ x, y }: { x: number; y: number }) {
  return (
    <>
      <rect x={x} y={y} width="7" height="7" rx="0.7" />
      <rect
        x={x + 1}
        y={y + 1}
        width="5"
        height="5"
        rx="0.48"
        fill="var(--deposit-qr-background, #f1f5f9)"
      />
      <rect x={x + 2} y={y + 2} width="3" height="3" rx="0.36" />
    </>
  );
}

function buildQrModules(value: string) {
  const seed = Array.from(value).reduce(
    (total, character) => total + character.charCodeAt(0),
    0,
  );
  const extraModules: ReadonlyArray<readonly [number, number]> =
    seed % 2 === 0
      ? [
          [13, 6], [17, 6], [21, 6], [6, 13], [23, 15], [15, 21], [21, 25],
        ]
      : [
          [15, 6], [19, 6], [21, 12], [6, 15], [24, 17], [13, 21], [19, 25],
        ];
  return [...QR_MODULES, ...extraModules];
}

interface DepositQrCodeProperties {
  value?: string;
}

export function DepositQrCode({
  value = "",
}: DepositQrCodeProperties): React.JSX.Element {
  const qrModules = buildQrModules(value);

  return (
    <svg
      className="deposit-qr"
      viewBox="0 0 29 29"
      role="img"
      aria-label="Deposit QR code"
    >
      <Finder x={0} y={0} />
      <Finder x={22} y={0} />
      <Finder x={0} y={22} />
      {qrModules.map(([x, y], index) => (
        <rect
          width="0.9"
          height="0.9"
          rx="0.14"
          x={x + 0.05}
          y={y + 0.05}
          key={`${x}-${y}-${index}`}
        />
      ))}
    </svg>
  );
}
